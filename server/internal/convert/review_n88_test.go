package convert_test

import (
	"context"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"fmt"
	"os"
	"testing"

	"configflow/internal/convert"
	"configflow/internal/jsonx"
)

// This review sample also runs unmodified on the pre-migration baseline, using
// only generator APIs that existed there. It checks all three engines without
// repeating the author's complete 4548-output run.
func TestN88ReviewByteSamples(t *testing.T) {
	var fixture struct {
		Baseline string            `json:"baseline"`
		Sources  map[string]string `json:"sources"`
		Cases    []struct {
			Source string `json:"source"`
			Row    int    `json:"row"`
			SHA256 string `json:"sha256"`
		} `json:"cases"`
	}
	data, err := os.ReadFile("testdata/n88_generation_bytes.json")
	if err != nil {
		t.Fatal(err)
	}
	if err = json.Unmarshal(data, &fixture); err != nil {
		t.Fatal(err)
	}
	if fixture.Baseline != "2277ce047d4abb78ffed436442c19b31152ba85d" {
		t.Fatal("baseline changed")
	}
	rows := map[string][]*jsonx.Object{}
	for name, digest := range fixture.Sources {
		data, err := os.ReadFile("testdata/" + name)
		if err != nil {
			t.Fatal(err)
		}
		sum := sha256.Sum256(data)
		if hex.EncodeToString(sum[:]) != digest {
			t.Fatal("source changed", name)
		}
		rows[name] = loadJSONLines(t, "testdata/"+name)
	}
	groups := map[string][]int{}
	for i, sample := range fixture.Cases {
		groups[rows[sample.Source][sample.Row].GetString("fn")] = append(groups[rows[sample.Source][sample.Row].GetString("fn")], i)
	}
	for _, fn := range []string{"generate", "loon", "surge"} {
		indices := groups[fn]
		if len(indices) < 3 {
			t.Fatal("missing engine", fn)
		}
		for _, at := range []int{0, len(indices) / 2, len(indices) - 1} {
			sample := fixture.Cases[indices[at]]
			t.Run(fmt.Sprintf("%s/%d", fn, sample.Row), func(t *testing.T) {
				entry := rows[sample.Source][sample.Row]
				args := entry.GetObject("args")
				profile := args.GetObject("profile").DeepCopy()
				restore := convert.SetMihomoEnvironment(corpusEnv(entry.GetObject("caches"), entry.GetObject("downloads")))
				defer restore()
				var out string
				var err error
				switch fn {
				case "generate":
					out, err = convert.GenerateMihomoConfig(context.Background(), profile, convert.GenerateOptions{BaseURL: args.GetString("base_url"), SyncLANHosts: args.GetBool("sync_lan_hosts"), SkipProviderPreflight: true, RegionProbe: args.GetBool("region_probe"), Report: jsonx.NewObject(), MihomoCoreVersion: args.Value("core_version"), ForAgent: args.GetBool("for_agent")})
				case "surge":
					out, err = convert.GenerateSurgeConfig(context.Background(), profile, args.GetString("base_url"))
				case "loon":
					out, err = convert.GenerateLoonConfig(context.Background(), profile, args.GetString("base_url"))
				}
				if err != nil {
					t.Fatal(err)
				}
				sum := sha256.Sum256([]byte(out))
				if hex.EncodeToString(sum[:]) != sample.SHA256 {
					t.Fatal("generated bytes changed")
				}
			})
		}
	}
}
