// Package version holds the build metadata the image build injects (release
// version and the paired Docker Agent image) and compares version strings:
// Agent versions such as "1.8.61-go" and release versions such as "v2.43.1".
// It does not read the environment or contact any registry.
package version

import "regexp"

// Version is the release the binary was built as. The image build sets it
// (Python rewrote `__version__ = "dev"` in version.py with sed):
//
//	go build -ldflags "-X configflow/internal/version.Version=${VERSION}"
//
// A local build reports "dev".
var Version = "dev"

// AgentImage is the Docker Agent image built from the same commit as this
// panel, for example "thsrite/config-flow-agent:2.0.0-rc.1". Release image
// builds set it next to Version:
//
//	go build -ldflags "-X configflow/internal/version.AgentImage=${AGENT_IMAGE}"
//
// Local, branch and autoupdate builds leave it empty and use DefaultAgentImage.
var AgentImage = ""

// DefaultAgentImage is the floating Docker Agent image used when the build did
// not name a paired one: the major-version tag, which follows every 3.x Agent
// release. `latest` stays on the last Python-era Agent until the maintainer
// moves it (PUBLISH_LATEST), so a Go panel must not fall back to it.
const DefaultAgentImage = "thsrite/config-flow-agent:3"

// imageReference accepts the Docker image references the installers emit
// unquoted: optional registry host[:port], repository path, optional tag or digest, no shell syntax.
var imageReference = regexp.MustCompile(`^([a-z0-9][a-z0-9.-]*(:[0-9]{1,5})?/)?[a-z0-9][a-z0-9._/-]*(:[A-Za-z0-9_][A-Za-z0-9_.-]{0,127})?(@sha256:[0-9a-f]{64})?$`)

// DockerAgentImage returns the Docker Agent image that new installations
// generated by this panel should run. A malformed build value falls back to
// DefaultAgentImage instead of reaching a generated shell command.
func DockerAgentImage() string {
	if AgentImage != "" && imageReference.MatchString(AgentImage) {
		return AgentImage
	}
	return DefaultAgentImage
}

// Information is the public build metadata. AgentImage is the Docker Agent
// image this panel pairs with; the Docker Agent update dialog defaults to it.
type Information struct {
	Version    string `json:"version"`
	AgentImage string `json:"agent_image"`
}

// Info returns the current release metadata.
func Info() Information { return Information{Version: Version, AgentImage: DockerAgentImage()} }
