const (
	// PreviewTTL is the immutable generated artifact lifetime.
	PreviewTTL = time.Hour
	// MaxPreviews bounds retained artifact directories.
	MaxPreviews = 24
	// MaxPreviewBytes includes archive AND private metadata/source bytes.
	MaxPreviewBytes = 512 << 20
)

var previewIDPattern = regexp.MustCompile(`^[a-f0-9]{32}$`)

// Identity is one captured target identity, including an opaque canonical JSON
// value. Identities preserves member order across Python-written metadata.
type Identity struct {
	ID    string
	Value json.RawMessage
}

// Identities is an ordered identity object; N8 replaces this small boundary codec.
type Identities []Identity

// MarshalJSON writes the original member order as a JSON object.
func (ids Identities) MarshalJSON() ([]byte, error) {
	var b bytes.Buffer
	b.WriteByte('{')
	for i, id := range ids {
		if i > 0 {
			b.WriteByte(',')
		}
		key, err := encodeJSON(id.ID)
		if err != nil {
			return nil, err
		}
		b.Write(key)
		b.WriteByte(':')
		if !json.Valid(id.Value) {
			return nil, fmt.Errorf("invalid preview identity")
		}
		b.Write(id.Value)
	}
	b.WriteByte('}')
	return b.Bytes(), nil
}

// UnmarshalJSON keeps Python's target ordering and rejects malformed identities.
func (ids *Identities) UnmarshalJSON(data []byte) error {
	d := json.NewDecoder(bytes.NewReader(data))
	token, err := d.Token()
	if err != nil || token != json.Delim('{') {
		return fmt.Errorf("invalid preview identities")
	}
	out := Identities{}
	seen := map[string]bool{}
	for d.More() {
		token, err = d.Token()
		if err != nil {
			return err
		}
		key, ok := token.(string)
		if !ok || key == "" || seen[key] || len(out) >= MaxFiles {
			return fmt.Errorf("invalid preview target identity")
		}
		var value json.RawMessage
		if err = d.Decode(&value); err != nil {
			return err
		}
		seen[key] = true
		out = append(out, Identity{key, value})
	}
	if _, err = d.Token(); err != nil {
		return err
	}
	*ids = out
	return nil
}

// PreviewInput captures everything needed to publish/export frozen generated bytes.
type PreviewInput struct {
	Target         Target
	Source         *Source
	ConfigRevision *Revision
	BaseURL        string
	Bundle         *Bundle
	ConfigContent  string
	Members        []Target
}

// Preview is a private frozen artifact record. Treat loaded values as immutable.
type Preview struct {
	ID             string          `json:"id"`
	ExpiresAt      int64           `json:"expires_at"`
	AgentID        string          `json:"agent_id"`
	ProfileID      string          `json:"profile_id"`
	ServiceType    string          `json:"service_type"`
	Identities     Identities      `json:"identities"`
	ConfigRevision *int64          `json:"config_revision"`
	InputDigest    string          `json:"input_digest"`
	Source         json.RawMessage `json:"source"`
	BaseURL        string          `json:"base_url"`
	DeploymentID   string          `json:"deployment_id"`
	ConfigContent  string          `json:"config_content"`
	BundleMeta     *BundleMeta     `json:"bundle_meta,omitempty"`
	Bundle         *Bundle         `json:"-"`
}

// BundleMeta records the immutable archive fields stored by Python previews.
type BundleMeta struct {
	Manifest         Manifest `json:"manifest"`
	SHA256           string   `json:"sha256"`
	ConfigVersion    string   `json:"config_version"`
	ComparisonConfig *File    `json:"comparison_config"`
}

// PreviewPublic is the frontend's final generated file view.
type PreviewPublic struct {
	ID           string   `json:"id"`
	DeploymentID string   `json:"deployment_id"`
	AgentID      string   `json:"agent_id"`
	ProfileID    string   `json:"profile_id"`
	ServiceType  string   `json:"service_type"`
	ExpiresAt    int64    `json:"expires_at"`
	Content      string   `json:"content"`
	ConfigPath   string   `json:"config_path"`
	Files        []File   `json:"files"`
	TargetIDs    []string `json:"target_ids"`
}

// Previews owns one data directory's artifacts and eviction under a single L4
// leaf-store mutex. Clock drives expiration in tests and production.
type Previews struct {
	dataDir   string
	clock     lifecycle.Clock
	writeFile func(context.Context, string, []byte) error
	mu        sync.Mutex
}

// NewPreviews creates the single preview owner; nil clock uses system time.
func NewPreviews(dataDir string, clock lifecycle.Clock) *Previews {
	return &Previews{dataDir: dataDir, clock: clock, writeFile: atomicWrite}
}
func (p *Previews) now() time.Time {
	if p.clock != nil {
		return p.clock.Now()
	}
	return time.Now()
}
func (p *Previews) root() string { return filepath.Join(p.dataDir, ".generated-previews") }

// Save writes a private artifact and evicts oldest/expired entries atomically
// under L4. Archive and source metadata both count toward the quota.
func (p *Previews) Save(ctx context.Context, in PreviewInput) (*Preview, error) {
	ctx = lifecycle.Detach(ctx)
	if err := ctx.Err(); err != nil {
		return nil, err
	}
	key, err := randomID()
	if err != nil {
		return nil, err
	}
	source, err := in.Source.snapshotJSON()
	if err != nil {
		return nil, err
	}
	revision := in.ConfigRevision
	if revision == nil && in.Source != nil && in.Source.revision != nil {
		revision = &Revision{Value: *in.Source.revision}
	}
	pv := Preview{ID: key, ExpiresAt: p.now().Unix() + int64(PreviewTTL/time.Second), AgentID: in.Target.ID, ProfileID: in.Source.ProfileID(), ServiceType: in.Target.ServiceType, Source: source, InputDigest: in.Source.inputDigest(), BaseURL: in.BaseURL, ConfigContent: in.ConfigContent, Identities: Identities{}}
	if pv.AgentID == "" || pv.ProfileID == "" {
		return nil, preparation("Missing preview target or profile identity")
	}
	if revision != nil && !revision.Null {
		value := revision.Value
		pv.ConfigRevision = &value
	}
	seen := map[string]bool{}
	for _, member := range in.Members {
		if member.ID == "" || seen[member.ID] {
			return nil, preparation("Missing or duplicate preview member identity")
		}
		seen[member.ID] = true
		pv.Identities = append(pv.Identities, Identity{member.ID, AgentIdentity(member)})
	}
	var archive []byte
	if in.Bundle != nil {
		archive, err = in.Bundle.Archive()
		if err != nil {
			return nil, err
		}
		sha, err := in.Bundle.SHA256()
		if err != nil {
			return nil, err
		}
		pv.BundleMeta = &BundleMeta{in.Bundle.Manifest(), sha, in.Bundle.ConfigVersion(), in.Bundle.Comparison()}
		pv.DeploymentID = in.Bundle.manifest.DeploymentID
		pv.ConfigContent = ""
	} else {
		pv.DeploymentID, err = randomID()
		if err != nil {
			return nil, err
		}
	}
	metadata, err := encodeJSON(pv)
	if err != nil {
		return nil, err
	}
	incoming := int64(len(metadata)) + int64(len(archive))
	if incoming > MaxPreviewBytes {
		return nil, preparation(msgPreviewLimit)
	}
	p.mu.Lock()
	defer p.mu.Unlock()
	// Keep the originating lifetime through quota inspection, eviction and each
	// atomic file replacement. Lock admission is not a publication point.
	if err = ctx.Err(); err != nil {
		return nil, err
	}
	if err = privateDir(p.root()); err != nil {
		return nil, err
	}
	folders, err := privateFolders(p.root())
	if err != nil {
		return nil, err
	}
	var total int64
	for _, folder := range folders {
		total += folder.size
	}
	for len(folders) > 0 && (len(folders) >= MaxPreviews || total+incoming > MaxPreviewBytes || folders[0].mtime < p.now().Add(-PreviewTTL).UnixNano()) {
		old := folders[0]
		folders = folders[1:]
		if err = ctx.Err(); err != nil {
			return nil, err
		}
		if err = os.RemoveAll(old.path); err != nil {
			return nil, err
		}
		total -= old.size
	}
	folder := filepath.Join(p.root(), key)
	if err = ctx.Err(); err != nil {
		return nil, err
	}
	if err = privateDir(folder); err != nil {
		return nil, err
	}
	completed := false
	defer func() {
		if !completed {
			_ = os.RemoveAll(folder)
		}
	}()
	if archive != nil {
		if err = p.writeFile(ctx, filepath.Join(folder, "bundle.tar.gz"), archive); err != nil {
			return nil, err
		}
	}
	if err = p.writeFile(ctx, filepath.Join(folder, "record.json"), metadata); err != nil {
		return nil, err
	}
	completed = true
	return p.load(key, in.Target.ID)
}

// Load refuses any missing, expired, evicted, foreign or corrupt preview.
func (p *Previews) Load(id, agentID string) (*Preview, error) {
	p.mu.Lock()
	defer p.mu.Unlock()
	return p.load(id, agentID)
}
func (p *Previews) load(id, agentID string) (*Preview, error) {
	if !previewIDPattern.MatchString(id) {
		return nil, &PreviewChanged{msgPreviewInvalid}
	}
	failure := func() (*Preview, error) { return nil, &PreviewChanged{msgPreviewUnavailable} }
	// The store root is not an artifact capability: following a replaced root
	// could import another repository's otherwise valid manual preview.
	info, err := os.Lstat(p.root())
	if err != nil || !info.IsDir() || info.Mode()&os.ModeSymlink != 0 {
		return failure()
	}
	folder := filepath.Join(p.root(), id)
	info, err = os.Lstat(folder)
	if err != nil || !info.IsDir() || info.Mode()&os.ModeSymlink != 0 {
		return failure()
	}
	raw, err := readPrivate(filepath.Join(folder, "record.json"), MaxPreviewBytes)
	if err != nil {
		return failure()
	}
	var pv Preview
	if jsondecode.Unmarshal(raw, &pv) != nil || pv.ID != id || pv.AgentID == "" || pv.AgentID != agentID || pv.ExpiresAt <= p.now().Unix() || pv.ProfileID == "" || pv.DeploymentID == "" {
		return failure()
	}
	if meta := pv.BundleMeta; meta != nil {
		if meta.Manifest.DeploymentID != pv.DeploymentID || meta.Manifest.AgentID != pv.AgentID || meta.Manifest.ProfileID != pv.ProfileID || meta.Manifest.ServiceType != pv.ServiceType {
			return failure()
		}
		archive, err := readPrivate(filepath.Join(folder, "bundle.tar.gz"), MaxPreviewBytes)
		if err != nil {
			return failure()
		}
		pv.Bundle, err = Open(meta.Manifest, archive, meta.SHA256, meta.ConfigVersion, meta.ComparisonConfig)
		if err != nil {
			return failure()
		}
	}
	return &pv, nil
}

// RequireCurrent proves the captured profile and every member still match.
func (p *Previews) RequireCurrent(ctx context.Context, m *agents.Manager, pv *Preview) error {
	src, revision, err := previewSnapshot(ctx, m, pv.ProfileID)
	if err != nil {
		return &PreviewChanged{msgPreviewProfileMissing}
	}
	if pv.ConfigRevision == nil || revision != *pv.ConfigRevision || src.inputDigest() != pv.InputDigest {
		return &PreviewChanged{msgPreviewConfigChanged}
	}
	for _, identity := range pv.Identities {
		target, ok, err := previewTarget(ctx, m, identity.ID)
		if err != nil {
			return err
		}
		if !ok || !equalJSON(AgentIdentity(target), identity.Value) {
			return &PreviewChanged{msgPreviewTargetChanged}
		}
	}
	return nil
}
func (pv *Preview) contents() (map[string]Content, []string, error) {
	if pv.Bundle == nil {
		return map[string]Content{"surge.conf": {[]byte(pv.ConfigContent), RoleConfig}}, []string{"surge.conf"}, nil
	}
	files, err := pv.Bundle.Contents()
	if err != nil {
		return nil, nil, err
	}
	order := make([]string, 0, len(pv.Bundle.manifest.Files))
	for _, f := range pv.Bundle.manifest.Files {
		order = append(order, f.Path)
	}
	return files, order, nil
}

// Public lists final immutable bytes and their file digests in manifest order.
func (pv *Preview) Public() PreviewPublic {
	result := PreviewPublic{ID: pv.ID, DeploymentID: pv.DeploymentID, AgentID: pv.AgentID, ProfileID: pv.ProfileID, ServiceType: pv.ServiceType, ExpiresAt: pv.ExpiresAt, ConfigPath: "surge.conf", Files: []File{}, TargetIDs: []string{}}
	if pv.Bundle != nil {
		result.ConfigPath = pv.Bundle.manifest.ConfigPath
	}
	for _, identity := range pv.Identities {
		result.TargetIDs = append(result.TargetIDs, identity.ID)
	}
	files, order, err := pv.contents()
	if err != nil {
		return result
	}
	result.Content = string(files[result.ConfigPath].Data)
	for _, name := range order {
		f := files[name]
		result.Files = append(result.Files, File{Path: name, Size: int64(len(f.Data)), SHA256: digest(f.Data), Role: f.Role})
	}
	return result
}

// Zip exports the frozen files as a native DEFLATE ZIP in manifest order.
func (pv *Preview) Zip() ([]byte, error) {
	files, order, err := pv.contents()
	if err != nil {
		return nil, err
	}
	var b bytes.Buffer
	zw := zip.NewWriter(&b)
	for _, p := range order {
		// Frozen exports contain configuration credentials. Match Python's
		// writestr permissions instead of the ZIP reader's default 0666.
		w, err := zw.CreateHeader(&zip.FileHeader{Name: p, Method: zip.Deflate, CreatorVersion: 3 << 8, ExternalAttrs: 0600 << 16})
		if err != nil {
			return nil, err
		}
		if _, err = w.Write(files[p].Data); err != nil {
			return nil, err
		}
	}
	if err = zw.Close(); err != nil {
		return nil, err
	}
	return b.Bytes(), nil
}

// File reads only a listed immutable member; missing/unsafe paths are absent.
func (pv *Preview) File(path string) ([]byte, bool, error) {
	p, err := RelativePath(path)
	if err != nil || p != path {
		return nil, false, nil
	}
	files, _, err := pv.contents()
	if err != nil {
		return nil, false, err
	}
	value, ok := files[p]
	return bytes.Clone(value.Data), ok, nil
}

// FinalizeBundle captures target-side final-preview adaptation before display.
func FinalizeBundle(ctx context.Context, m *agents.Manager, t Target, b *Bundle, src *Source) (*Bundle, error) {
	capability, err := queryCapabilities(ctx, m, t)
	if err != nil {
		return nil, err
	}
	supported := false
	for _, v := range capability.FinalConfigProtocols {
		supported = supported || v == 1
	}
	if !supported || capability.ServiceType != t.ServiceType {
		return nil, preparation(msgUpdateForPreview)
	}
	path := capability.ConfigPath
	if path == "" {
		path = "config.yaml"
	}
	b, err = Retarget(b, path)
	if err != nil {
		return nil, err
	}
	var comparison *File
	for _, f := range b.manifest.Files {
		if f.Role == RoleConfig {
			copy := f
			comparison = &copy
			break
		}
	}
	if t.ServiceType == "mihomo" {
		b, err = PrepareMihomoResources(ctx, b, capability, src, Progress{})
		if err != nil {
			return nil, err
		}
	}
	files, err := b.Contents()
	if err != nil {
		return nil, err
	}
	content, err := finalPreview(ctx, m, t, string(files[path].Data))
	if err != nil {
		return nil, err
	}
	files[path] = Content{[]byte(content), RoleConfig}
	manifest := b.Manifest()
	manifest.FinalConfig = true
	for i, f := range manifest.Files {
		if f.Role == RoleConfig {
			manifest.Files[i].Size = int64(len(content))
			manifest.Files[i].SHA256 = digest([]byte(content))
		}
	}
	return Pack(manifest, files, digest([]byte(content))[:8], comparison)
}
